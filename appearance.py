def build_character_sprite(app_data):
    """Собирает 16x16 спрайт персонажа из словаря внешности app_data"""
    surf = pygame.Surface((16, 16), pygame.SRCALPHA)
    custom_pal = dict(PALETTE)

    skin_idx = app_data.get("skin", 0) % len(SKIN_COLORS)
    hair_idx = app_data.get("hair_color", 0) % len(HAIR_COLORS)
    eye_idx = app_data.get("eye_color", 0) % len(EYE_COLORS)
    cloth_idx = app_data.get("cloth_color", 0) % len(CLOTH_COLORS)

    _, s_main, s_dark = SKIN_COLORS[skin_idx]
    _, h_main, h_dark = HAIR_COLORS[hair_idx]
    _, e_col = EYE_COLORS[eye_idx]
    _, c_main, c_dark = CLOTH_COLORS[cloth_idx]

    custom_pal["S"], custom_pal["s"] = s_main, s_dark
    custom_pal["H"], custom_pal["h"] = h_main, h_dark
    custom_pal["E"] = e_col
    custom_pal["C"], custom_pal["c"] = c_main, c_dark
    custom_pal["L"] = (85, 65, 45)

    layers = [
        BODY_LAYERS.get(app_data.get("body", "tunic"), BODY_LAYERS["tunic"])["matrix"],
        HEAD_LAYERS.get(app_data.get("head", "human"), HEAD_LAYERS["human"])["matrix"],
        HAIR_LAYERS.get(app_data.get("hair", "short"), HAIR_LAYERS["short"])["matrix"],
    ]

    for matrix in layers:
        for r, row in enumerate(matrix[:16]):
            for c, ch in enumerate(row[:16]):
                col = custom_pal.get(ch)
                if col:
                    surf.set_at((c, r), col)

    return surf

def generate_random_appearance(race_id="human"):
    """Генерирует случайную внешность для горожанина или странника"""
    head_map = {"human": "human", "elf": "elf", "goblin": "goblin", "skeleton": "skull"}
    skin_default = 3 if race_id == "goblin" else (4 if race_id == "skeleton" else random.randint(0, 2))
    return {
        "body": random.choice(list(BODY_LAYERS.keys())),
        "head": head_map.get(race_id, "human"),
        "hair": "bald" if race_id == "skeleton" else random.choice(list(HAIR_LAYERS.keys())),
        "skin": skin_default,
        "hair_color": random.randint(0, len(HAIR_COLORS) - 1),
        "eye_color": 3 if race_id in ("goblin", "skeleton") else random.randint(0, 2),
        "cloth_color": random.randint(0, len(CLOTH_COLORS) - 1),
    }